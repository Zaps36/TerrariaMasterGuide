/** Resolve the evil-specific boss for the current world. */
export function evilBossId(evil) {
  return evil === 'crimson' ? 'brain_of_cthulhu' : 'eater_of_worlds';
}

/** Bosses relevant to a world: hides the other evil's boss. */
export function bossesForWorld(evil) {
  const hidden = evil === 'crimson' ? 'eater_of_worlds' : 'brain_of_cthulhu';
  return BOSSES.filter((b) => b.id !== hidden);
}

/** Preparation objective key for a boss checklist entry. */
export function prepKey(bossId, entry) {
  return entry.global || `boss:${bossId}:${entry.id}`;
}
